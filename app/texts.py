def consent_text() -> str:
    """Отдельное сообщение согласия, до сохранения имени и телефона."""
    if not PRIVACY_POLICY_URL and not DEMO_MODE:
        return CONSENT_UNAVAILABLE
    policy = (
        "📄 Политика обработки персональных данных — по кнопке ниже.\n\n"
        if PRIVACY_POLICY_URL else
        "🧪 Демонстрация: политика не опубликована. "
        "Используйте только вымышленные данные, не отправляйте настоящий номер телефона.\n\n"
    )
    return (
        f"🛡 <b>Обработка персональных данных</b>\n\n"
        f"Бот компьютерного клуба <b>{CLUB_NAME}</b> обрабатывает ваши "
        "персональные данные: имя, номер телефона, имя пользователя Telegram — "
        "для бронирования мест и обратной связи.\n\n"
        f"Оператор персональных данных — клуб <b>{CLUB_NAME}</b>.\n"
        f"{policy}"
        "Пожалуйста, подтвердите согласие на обработку данных в соответствии "
        "с Федеральным законом № 152-ФЗ отдельной кнопкой «✅ Я согласен».\n\n"
        "Отозвать согласие можно кнопкой «Отозвать согласие» в главном меню."
    )

